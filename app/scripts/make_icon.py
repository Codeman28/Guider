"""Draws the Guider app icon (a tear-off calendar sheet with a glue strip and a "G" numeral) from
design/tokens.json. Provenance: generated by this script, no external artwork.

Usage: engine/.venv/Scripts/python app/scripts/make_icon.py  → app/src-tauri/icons/source.png
then:  cd app && npx tauri icon src-tauri/icons/source.png
"""
import json
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
ui = json.loads((ROOT / "design" / "tokens.json").read_text(encoding="utf-8"))["color"]["ui"]
S = 1024
img = Image.new("RGBA", (S, S), (0, 0, 0, 0))
d = ImageDraw.Draw(img)
pad, r = 96, 72
d.rounded_rectangle((pad, pad, S - pad, S - pad), radius=r, fill=ui["white"], outline=ui["edge"], width=12)
d.rounded_rectangle((pad, pad, S - pad, pad + 150), radius=r, fill=ui["glue"])
d.rectangle((pad, pad + 80, S - pad, pad + 150), fill=ui["glue"])
font = None
for name in ("bahnschrift.ttf", "arialbd.ttf"):
    try:
        font = ImageFont.truetype(name, 560)
        break
    except OSError:
        continue
d.text((S / 2, S / 2 + 90), "G", fill=ui["ink"], font=font or ImageFont.load_default(560), anchor="mm")
out = ROOT / "app" / "src-tauri" / "icons" / "source.png"
out.parent.mkdir(parents=True, exist_ok=True)
img.save(out)
print(out)
